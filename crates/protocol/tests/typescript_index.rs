// Cargo runs the unit tests of this crate before this file, so each binding exists when the index is written

use std::fs;
use std::path::{Path, PathBuf};

const INDEX_FILE: &str = "index.ts";

fn export_dir() -> PathBuf {
    let dir = std::env::var("TS_RS_EXPORT_DIR")
        .expect("TS_RS_EXPORT_DIR is unset, run cargo from the repository root");
    PathBuf::from(dir)
}

fn binding_files(dir: &Path) -> Vec<PathBuf> {
    let mut files = Vec::new();
    for entry in fs::read_dir(dir).expect("export directory is readable") {
        let path = entry.expect("directory entry is readable").path();
        if path.is_dir() {
            files.extend(binding_files(&path));
        } else if path.extension().is_some_and(|extension| extension == "ts")
            && path.file_name().is_some_and(|name| name != INDEX_FILE)
        {
            files.push(path);
        }
    }
    files
}

fn export_statement(file: &Path, root: &Path) -> String {
    let module = file
        .strip_prefix(root)
        .expect("binding is inside the export directory")
        .with_extension("");
    let type_name = module
        .file_name()
        .expect("binding has a file name")
        .to_string_lossy();
    let module_path = module
        .components()
        .map(|component| component.as_os_str().to_string_lossy())
        .collect::<Vec<_>>()
        .join("/");
    format!("export type {{ {type_name} }} from \"./{module_path}\"")
}

#[test]
fn bindings_use_number_for_each_integer() {
    for file in binding_files(&export_dir()) {
        let binding = fs::read_to_string(&file).expect("binding is readable");
        assert!(
            !binding.contains("bigint"),
            "{} holds a bigint",
            file.display()
        );
    }
}

#[test]
fn index_reexports_each_binding() {
    let root = export_dir();
    let mut statements: Vec<String> = binding_files(&root)
        .iter()
        .map(|file| export_statement(file, &root))
        .collect();
    statements.sort();
    assert!(!statements.is_empty(), "no binding in {}", root.display());

    let index = format!(
        "// Generated by `cargo test -p protocol`. Do not edit this file manually.\n\n{}\n",
        statements.join("\n")
    );
    fs::write(root.join(INDEX_FILE), index).expect("index is writable");
}
